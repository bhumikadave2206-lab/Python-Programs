# (18) Python program to create tuple objects in different ways

t1 = ()
# Tuple with values
t2 = (1, 2, 3,9,7)
# Tuple from list
t3 = tuple([4, 5, 6,9,7,6])
# Tuple with mixed data types
t4 = (10, "python", 3.14)
print("Empty tuple:", t1)
print("Tuple with values:", t2)
print("Tuple from list:", t3)
print("Mixed tuple:", t4)